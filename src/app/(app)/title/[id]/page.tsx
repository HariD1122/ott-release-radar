import FollowButton from "@/components/FollowButton";
import TitleCard from "@/components/TitleCard";
import { dateText } from "@/lib/text";
import { requireUser } from "@/lib/auth/auth";
import { followedIds, getRelease } from "@/lib/catalogue";
import { q } from "@/lib/db";
import type { PlatformDetail } from "@/lib/platforms";
import { notFound } from "next/navigation";

const DATE_TYPE: Record<string, string> = {
  ott_digital_in: "India digital (OTT) release date, from TMDB",
  tv_season_air_date: "Season air date, from TMDB (not region specific)",
  tv_episode_air_date: "Episode air date, from TMDB (not region specific)",
};

export default async function TitlePage({ params }: { params: Promise<{ id: string }> }) {
  const user = await requireUser();
  const r = await getRelease(user.id, (await params).id);
  if (!r) notFound();
  const [extra, followed] = await Promise.all([
    q<{ platform_details: PlatformDetail[]; verification_status: string; last_fetched_at: string; rec_conf: string | null; limits: string[] | null; model_id: string | null }>(
      `SELECT r.platform_details, r.verification_status, r.last_fetched_at, rec.confidence::text AS rec_conf, rec.data_limitations AS limits, rec.model_id
       FROM releases r LEFT JOIN recommendations rec ON rec.release_id = r.id AND rec.user_id = $2 WHERE r.id = $1`,
      [r.id, user.id],
    ),
    followedIds(user.id),
  ]);
  const e = extra[0];
  return (
    <article>
      {r.backdrop_url && (
        // eslint-disable-next-line @next/next/no-img-element
        <img src={r.backdrop_url} alt="" className="mb-6 h-48 w-full rounded-xl border border-line object-cover object-top shadow-sm md:h-72" />
      )}
      <div className="grid items-start gap-8 md:grid-cols-[280px_minmax(0,1fr)]">
        <TitleCard release={r} wide rec={r.rec_decision && r.rec_explanation ? { decision: r.rec_decision, reason: r.rec_explanation } : null} />
        <div>
          <h1 className="text-3xl font-extrabold tracking-tight">{r.title}</h1>
          {r.episode_title && <p className="mt-1 text-accent">S{r.season_number}E{r.episode_number} — {r.episode_title}</p>}
          <p className="mt-3 max-w-2xl text-sm leading-relaxed text-ink/90">{r.synopsis ?? "Synopsis unavailable."}</p>
          <dl className="mt-5 grid max-w-2xl grid-cols-[150px_1fr] gap-x-4 gap-y-2 text-sm">
            <dt className="text-muted">Release date</dt><dd>{dateText(r)}</dd>
            <dt className="text-muted">Date meaning</dt><dd>{DATE_TYPE[r.release_date_type] ?? "Unverified"}</dd>
            <dt className="text-muted">Verification</dt><dd>{e.verification_status === "verified" ? "Exact timestamp" : "Date only (no exact time from source)"}</dd>
            <dt className="text-muted">Platforms (India)</dt>
            <dd>
              {r.platforms.length ? r.platforms.join(", ") : "Not confirmed"}{" "}
              <span className="text-xs text-muted">
                ({r.platform_status === "confirmed_both" ? "TMDB and RapidAPI agree" : r.platform_status === "tmdb_only" ? "TMDB only" : r.platform_status === "rapidapi_only" ? "RapidAPI only" : "no source confirms"})
              </span>
            </dd>
            {e.platform_details.some((d) => d.kind === "rent" || d.kind === "buy" || d.kind === "store") && (
              <><dt className="text-muted">Rent / buy / store</dt><dd>{[...new Set(e.platform_details.filter((d) => d.kind === "rent" || d.kind === "buy" || d.kind === "store").map((d) => d.name))].join(", ")}</dd></>
            )}
            <dt className="text-muted">Genres</dt><dd>{r.genres.join(", ") || "Unavailable"}</dd>
            <dt className="text-muted">Languages</dt><dd>{r.languages.join(", ") || "Unavailable"}</dd>
            {r.runtime_minutes && <><dt className="text-muted">Runtime</dt><dd>{r.runtime_minutes} min</dd></>}
            {r.episode_count && <><dt className="text-muted">Episodes</dt><dd>{r.episode_count}</dd></>}
            {r.vote_average && <><dt className="text-muted">TMDB rating</dt><dd>{r.vote_average}</dd></>}
            {r.release_note && <><dt className="text-muted">Release note</dt><dd>{r.release_note}</dd></>}
            <dt className="text-muted">Last fetched</dt><dd>{new Date(e.last_fetched_at).toLocaleString("en-IN", { timeZone: "Asia/Kolkata" })} IST</dd>
          </dl>
          {r.rec_explanation && (
            <div className="mt-5 max-w-2xl rounded-xl border border-line bg-surface p-3 text-sm">
              <b>AI opinion ({r.rec_decision})</b> <span className="text-xs text-muted">— generated by {e.model_id}, not a source of facts</span>
              <p className="mt-1">{r.rec_explanation}</p>
              {e.limits && e.limits.length > 0 && <p className="mt-1 text-xs text-muted">Limitations: {e.limits.join("; ")}</p>}
            </div>
          )}
          <div className="mt-5 flex flex-wrap items-center gap-3">
            {r.series_tmdb_id && <FollowButton seriesTmdbId={r.series_tmdb_id} title={r.title} initial={followed.includes(r.series_tmdb_id)} />}
            {r.source_url && <a className="btn" href={r.source_url} target="_blank" rel="noreferrer">View on TMDB</a>}
          </div>
        </div>
      </div>
    </article>
  );
}
